function upc(body, addon) {
  if (body.length !== 12 || addon.length !== 5) {
    throw new Error(`Barcode parts must be 12+5, got ${body.length}+${addon.length}`);
  }
  return `${body}${addon}`;
}

function row(overrides) {
  const record = { ...defaults, ...overrides };
  if (!record["Full Title"]) record["Full Title"] = `${record.Series} #${record.Issue}`;
  if (!record.Title) record.Title = record.Series;
  for (const header of HEADERS) {
    if (!(header in record)) throw new Error(`Missing ${header}`);
  }
  return HEADERS.map((header) => record[header] ?? "");
}

function encode(value) {
  const text = value == null ? "" : String(value);
  if (/[",\r\n]/.test(text)) return `"${text.replace(/"/g, '""')}"`;
  return text;
}

